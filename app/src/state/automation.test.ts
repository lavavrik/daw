import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { MIX_PARAMS } from '../audio/mixerCatalog';
import { moduleDef } from '../audio/catalog';
import { toPos } from '../ui/rack/knobMath';
import { automatableParams, laneCount, targetDef, laneSetCommand, laneValueAt, nextBreakpoint, pointCommands, thin } from './automation';
import { laneCommands } from '../project/commands';
import { trackPatch } from './patches';
import { AUTO_KIND, MIX_MASTER, packAutoParam } from '../audio/protocol';
import { paramIndex } from '../audio/catalog';
import type { PointTuple } from './automation';
import { MAX_AUTO_POINTS, Op } from '../audio/protocol';
import { blankModel, run } from '../history/engineModel';
import { addLane } from './automation-actions';
import { addDrumTrack } from './actions';
import { addAudioTrack } from './audio-actions';
import { addSynthTrack } from './rack-actions';
import { Project } from './project.svelte';

const nullSink = { send: () => true };

interface Case {
  name: string;
  param: { min: number; max: number; curve: 'lin' | 'exp' };
  points: [number, number, number][];
  queries: [number, number][];
}

describe('automation (pure)', () => {
  it('laneValueAt matches the engine fixture', () => {
    // engine/tests/fixtures/auto_eval.json: generated by the engine's
    // `lane_eval_matches_fixture` (Task 1); the same lanes and queries here.
    const fx = JSON.parse(readFileSync(new URL('../../../engine/tests/fixtures/auto_eval.json', import.meta.url), 'utf8')) as { cases: Case[] };
    expect(fx.cases.length).toBeGreaterThanOrEqual(7);
    for (const c of fx.cases) {
      const param = { ...c.param, default: c.param.min, integer: false };
      // The model keeps points sorted by tick; the fixture lists them in send order.
      const points = c.points.map(([tick, value, hold]) => ({ tick, value, hold: hold === 1 })).sort((a, b) => a.tick - b.tick);
      for (const [tick, want] of c.queries) {
        const got = laneValueAt(points, tick, param);
        expect(got, `${c.name} @ ${tick}`).not.toBeNull();
        // Compared in knob space (exp params: the knob position), to 1e-6.
        expect(Math.abs(toPos(param as never, got!) - toPos(param as never, want)), `${c.name} @ ${tick}: ${got} vs ${want}`).toBeLessThan(1e-6);
      }
    }
    expect(laneValueAt([], 0, { min: 0, max: 1, curve: 'lin', default: 0, integer: false })).toBeNull();
  });

  it('nextBreakpoint is the first point after the tick', () => {
    const pts = [{ tick: 0, value: 0, hold: false }, { tick: 960, value: 1, hold: true }, { tick: 1920, value: 0, hold: false }];
    expect(nextBreakpoint(pts, -1)?.tick).toBe(0);
    expect(nextBreakpoint(pts, 0)?.tick).toBe(960);
    expect(nextBreakpoint(pts, 959.5)?.tick).toBe(960);
    expect(nextBreakpoint(pts, 960)?.tick).toBe(1920);
    expect(nextBreakpoint(pts, 1920)).toBeNull();
    expect(nextBreakpoint([], 0)).toBeNull();
  });

  it('thin keeps a sweep within tolerance', () => {
    // A freehand sweep: a sine over two bars, one sample every 10 ticks, in knob position.
    const samples = Array.from({ length: 769 }, (_, i) => ({ tick: i * 10, value: 0.5 + 0.4 * Math.sin(i / 60) }));
    const tol = 0.005;
    const kept = thin(samples, tol);
    // Far fewer points, the ends kept, in order, every kept point one of the samples.
    expect(kept.length).toBeLessThan(samples.length / 5);
    expect(kept.length).toBeGreaterThan(4);
    expect(kept[0]).toEqual(samples[0]);
    expect(kept.at(-1)).toEqual(samples.at(-1));
    for (let i = 1; i < kept.length; i++) expect(kept[i].tick).toBeGreaterThan(kept[i - 1].tick);
    for (const k of kept) expect(samples).toContainEqual(k);
    // Every sample is within the tolerance of the line through the kept points.
    const lin = { min: 0, max: 1, curve: 'lin' as const, default: 0, integer: false };
    const pts = kept.map((k) => ({ ...k, hold: false }));
    for (const s of samples) expect(Math.abs(laneValueAt(pts, s.tick, lin)! - s.value)).toBeLessThanOrEqual(tol + 1e-12);
    // A straight line thins to its two ends; a short input is returned as is.
    const line = Array.from({ length: 50 }, (_, i) => ({ tick: i, value: i / 49 }));
    expect(thin(line, tol)).toEqual([line[0], line[49]]);
    expect(thin(line.slice(0, 2), tol)).toEqual(line.slice(0, 2));
    expect(thin([], tol)).toEqual([]);
  });

  it('automatableParams: continuous mixer params, then each module\'s, by name', () => {
    const p = new Project();
    const drums = addDrumTrack(p, nullSink)!;
    const synth = addSynthTrack(p, nullSink)!;
    const audio = addAudioTrack(p, nullSink)!;
    const trackMix = MIX_PARAMS.filter((d) => !d.integer && d.appliesTo.includes('track') && d.group !== 'reverb' && d.group !== 'delay');
    const names = (xs: { target: { kind: string; param: string } }[]) => xs.map((x) => x.target.param);
    expect(names(automatableParams(drums))).toEqual(trackMix.map((d) => d.name));
    expect(names(automatableParams(audio))).toEqual(trackMix.map((d) => d.name)); // Audio slots: mixer targets only
    const sp = automatableParams(synth);
    expect(names(sp.slice(0, trackMix.length))).toEqual(trackMix.map((d) => d.name));
    const rack = sp.slice(trackMix.length);
    expect(rack.length).toBeGreaterThan(0);
    for (const x of rack) {
      if (x.target.kind !== 'rack') throw new Error('kind');
      const m = synth.modules.find((y) => y.idx === (x.target as { module: number }).module)!;
      const def = moduleDef(m.kind).params.find((d) => d.name === x.target.param)!;
      expect(def.integer).toBe(false);
    }
    expect(rack.some((x) => x.target.param === 'cutoff')).toBe(true);
    expect(rack.some((x) => x.target.param === 'wave' || x.target.param === 'voices')).toBe(false);
    // Integer, choice and flag params are never offered.
    for (const x of [...sp, ...automatableParams('reverb'), ...automatableParams('delay'), ...automatableParams('master')]) {
      expect(x.def.integer).toBe(false);
    }
    expect(names(automatableParams('master'))).toEqual(['fader', 'eq_hp', 'eq_low', 'eq_mid_freq', 'eq_mid_gain', 'eq_mid_q', 'eq_high', 'limiter_ceiling']);
    expect(names(automatableParams('reverb'))).toContain('rev_size');
    expect(names(automatableParams('reverb'))).not.toContain('delay_feedback');
    expect(names(automatableParams('delay'))).toEqual(expect.arrayContaining(['delay_feedback', 'delay_high_cut', 'pan']));
    expect(names(automatableParams('delay'))).not.toContain('delay_time');
  });

  it('a Scope\'s params are never automation targets (they only change the view)', () => {
    const p = new Project();
    const synth = addSynthTrack(p, nullSink)!;
    synth.modules.push({ idx: 30, kind: moduleDef('scope').kind, params: moduleDef('scope').params.map((d) => d.default) });
    expect(automatableParams(synth).some((x) => x.target.kind === 'rack' && x.target.module === 30)).toBe(false);
    for (const param of ['time', 'gain_a', 'gain_b']) expect(targetDef(synth, { kind: 'rack', module: 30, param })).toBeNull();
    expect(automatableParams(synth).some((x) => x.target.param === 'cutoff')).toBe(true);
  });

  it('one AUTO_LANE_SET builder: the live lane and its saved form encode the same target', () => {
    const p = new Project();
    const synth = addSynthTrack(p, nullSink)!;
    const drums = addDrumTrack(p, nullSink)!;
    const patch = trackPatch(synth, (id) => id);
    const json = (t: { kind: 'mix'; param: string } | { kind: 'rack'; module: number; param: string }) => ({
      lane: 5, enabled: true, points: [] as [number, number, 0 | 1][],
      target: t.kind === 'mix' ? { mix: t.param } : { rack: [t.module, t.param] as [number, string] },
    });
    for (const { target } of automatableParams(synth)) {
      expect(laneSetCommand(5, synth, target)).toEqual(laneCommands(json(target), synth.slot, patch)[0]);
    }
    for (const { target } of automatableParams('master')) {
      expect(laneSetCommand(5, 'master', target)).toEqual(laneCommands(json(target), MIX_MASTER, null)[0]);
    }
    const filter = synth.modules.find((m) => m.kind === moduleDef('filter').kind)!;
    expect(laneSetCommand(7, synth, { kind: 'rack', module: filter.idx, param: 'cutoff' }))
      .toEqual([Op.AUTO_LANE_SET, 7, AUTO_KIND.RACK, synth.slot, packAutoParam(filter.idx, paramIndex(moduleDef('filter'), 'cutoff'))]);
    expect(laneSetCommand(1, drums, { kind: 'mix', param: 'pan' })).toEqual([Op.AUTO_LANE_SET, 1, AUTO_KIND.MIX, drums.slot, 1]);
  });

  it('laneCount counts every track\'s lanes and the Master row\'s', () => {
    const p = new Project();
    const d = addDrumTrack(p, nullSink)!;
    expect(laneCount(p)).toBe(0);
    addLane(p, nullSink, d.id, { kind: 'mix', param: 'fader' });
    addLane(p, nullSink, 'master', { kind: 'mix', param: 'limiter_ceiling' });
    expect(laneCount(p)).toBe(2);
  });

  it('pointCommands: random lane diffs never hit a taken tick (removals first)', () => {
    // A seeded random walk of lane states: moves that swap or overlap ticks,
    // removals and inserts, each turned into commands by pointCommands and
    // applied to the modelled engine (which refuses a tick another point of
    // the lane still holds, as engine/src/automation.rs Lane::set_point does).
    let seed = 7;
    const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 2 ** 32);
    const int = (n: number) => Math.floor(rnd() * n);
    const fader = MIX_PARAMS.find((d) => d.name === 'fader')!;
    for (let round = 0; round < 60; round++) {
      const m = run(blankModel(), [[Op.ADD_DRUM_TRACK, 0], [Op.AUTO_LANE_SET, 3, 1, 0, fader.id]]);
      let from = new Map<number, PointTuple>();
      for (let step = 0; step < 12; step++) {
        // A new state: some points kept (maybe moved by a shared offset or
        // shuffled onto each other's ticks), some removed, some inserted;
        // dense idx 0..n-1, unique ticks.
        const ticks = [...from.values()].map((x) => x[0]);
        const n = Math.min(MAX_AUTO_POINTS, Math.max(0, ticks.length + int(9) - 4));
        const pool = new Set<number>();
        const shift = int(3) === 0 ? 0 : int(5) * 10 - 20;
        for (const t of ticks) if (int(4) > 0) pool.add(Math.max(0, t + shift));
        while (pool.size < n) pool.add(int(40) * 10);
        let next = [...pool].slice(0, n);
        if (int(2)) next = next.sort(() => rnd() - 0.5); // ticks land on other idx: swaps
        const to = new Map<number, PointTuple>(next.map((t, i) => [i, [t, -int(60), int(2) as 0 | 1]]));
        const cmds = pointCommands(3, from, to);
        const ops = cmds.map((c) => c[0]);
        const lastRemove = ops.lastIndexOf(Op.AUTO_POINT_REMOVE);
        const firstSet = ops.indexOf(Op.AUTO_POINT_SET);
        if (lastRemove >= 0 && firstSet >= 0) expect(lastRemove).toBeLessThan(firstSet);
        run(m, cmds);
        expect(m.errors, `round ${round} step ${step}`).toEqual([]);
        const lane = m.autos[3]!;
        expect(Object.fromEntries(Object.entries(lane.points))).toEqual(Object.fromEntries([...to].map(([i, p]) => [i, [...p]])));
        // Nothing to do when nothing changed.
        expect(pointCommands(3, to, to)).toEqual([]);
        from = to;
      }
    }
  });
});
