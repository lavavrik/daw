// Parity between the built-in patches and their engine fixtures:
//   - the starter patches (patches.ts) -> engine/tests/fixtures/starter_patches.txt,
//     replayed by engine/tests/starter_patches.rs to check that no starter
//     patch clips the master bus (plan-2 final review I2);
//   - the House set (housePatches.ts) -> engine/tests/fixtures/house_patches.txt,
//     replayed by engine/tests/house_patches.rs (levels, clipping, release,
//     the Sax acceptance numbers), no_alloc.rs and perf.rs. Each house block
//     also has a "phrase <chord4|chord5|bass|lead|arp>" line: what the level, peak
//     and CPU tests play on it.
//
// Why a fixture: the patch data lives in TS and the engine tests can't run
// TS, and parsing patches.ts (or a JSON copy) in Rust would need serde or a
// hand-rolled parser. A flat "op a b c d" command list is trivial to parse in
// Rust and is exactly what the UI sends, so the test exercises the real
// command path (addSynthTrack -> loadPatch -> selectTrack).
//
// After changing a built-in patch, regenerate both with:
//   UPDATE_FIXTURES=1 npx vitest run app/src/state/patches.fixture.test.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { Project } from './project.svelte';
import { HOUSE_GROUPS, HOUSE_PHRASES } from './housePatches';
import type { Patch } from './patches';
import { STARTER_PATCHES } from './patches';
import { addSynthTrack } from './rack-actions';

const STARTER_FIXTURE = new URL('../../../engine/tests/fixtures/starter_patches.txt', import.meta.url);
const HOUSE_FIXTURE = new URL('../../../engine/tests/fixtures/house_patches.txt', import.meta.url);

/**
 * Commands the UI sends to add a synth track (slot 0) holding each patch, as
 * fixture text. `phrase` (house set only) adds a "phrase <kind>" line after
 * each "patch <name>" line.
 */
function fixtureText(source: string, patches: Patch[], phrase?: (name: string) => string): string {
  const lines = [
    `# Generated by app/src/state/patches.fixture.test.ts from app/src/state/${source}.`,
    '# Do not edit by hand. One block per patch: "patch <name>",' + (phrase ? ' "phrase <kind>",' : '') + ' then the',
    '# commands addSynthTrack sends on a fresh project, one per line: op a b c d.',
  ];
  for (const patch of patches) {
    const sent: number[][] = [];
    const sink = {
      send(op: number, a = 0, b = 0, c = 0, d = 0) {
        sent.push([op, a, b, c, d]);
        return true;
      },
    };
    addSynthTrack(new Project(), sink, 'Synth', patch);
    lines.push(`patch ${patch.name}`);
    if (phrase) lines.push(`phrase ${phrase(patch.name)}`);
    for (const s of sent) lines.push(s.join(' '));
  }
  return lines.join('\n') + '\n';
}

function housePhrase(name: string): string {
  const p = HOUSE_PHRASES[name];
  if (!p) throw new Error(`house patch "${name}" has no phrase in HOUSE_PHRASES`);
  return p;
}

describe('built-in patch engine fixtures', () => {
  it('starter: matches what loadPatch sends (regenerate with UPDATE_FIXTURES=1)', () => {
    const want = fixtureText('patches.ts', STARTER_PATCHES);
    if (process.env.UPDATE_FIXTURES) writeFileSync(STARTER_FIXTURE, want);
    expect(readFileSync(STARTER_FIXTURE, 'utf8')).toBe(want);
  });
  it('house: matches what loadPatch sends, with each phrase (regenerate with UPDATE_FIXTURES=1)', () => {
    const want = fixtureText('housePatches.ts', HOUSE_GROUPS.flatMap((g) => g.patches), housePhrase);
    if (process.env.UPDATE_FIXTURES) writeFileSync(HOUSE_FIXTURE, want);
    expect(readFileSync(HOUSE_FIXTURE, 'utf8')).toBe(want);
  });
});
