// Parity between the starter patches (patches.ts) and the engine fixture
// engine/tests/fixtures/starter_patches.txt, which the Rust test
// engine/tests/starter_patches.rs replays through `Engine::command` to check
// that no starter patch clips the master bus (plan-2 final review I2).
//
// Why a fixture: the patch data lives in TS and the engine tests can't run
// TS, and parsing patches.ts (or a JSON copy) in Rust would need serde or a
// hand-rolled parser. A flat "op a b c d" command list is trivial to parse in
// Rust and is exactly what the UI sends, so the test exercises the real
// command path (addSynthTrack -> loadPatch -> selectTrack).
//
// After changing a starter patch, regenerate with:
//   UPDATE_FIXTURES=1 npx vitest run app/src/state/patches.fixture.test.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { Project } from './project.svelte';
import { STARTER_PATCHES } from './patches';
import { addSynthTrack } from './rack-actions';

const FIXTURE = new URL('../../../engine/tests/fixtures/starter_patches.txt', import.meta.url);

/** Commands the UI sends to add a synth track (slot 0) holding `patch`, as fixture text. */
function fixtureText(): string {
  const lines = [
    '# Generated by app/src/state/patches.fixture.test.ts from app/src/state/patches.ts.',
    '# Do not edit by hand. One block per starter patch: "patch <name>", then the',
    '# commands addSynthTrack sends on a fresh project, one per line: op a b c d.',
  ];
  for (const patch of STARTER_PATCHES) {
    const sent: number[][] = [];
    const sink = {
      send(op: number, a = 0, b = 0, c = 0, d = 0) {
        sent.push([op, a, b, c, d]);
        return true;
      },
    };
    addSynthTrack(new Project(), sink, 'Synth', patch);
    lines.push(`patch ${patch.name}`);
    for (const s of sent) lines.push(s.join(' '));
  }
  return lines.join('\n') + '\n';
}

describe('starter patch engine fixture', () => {
  it('matches what loadPatch sends (regenerate with UPDATE_FIXTURES=1)', () => {
    const want = fixtureText();
    if (process.env.UPDATE_FIXTURES) writeFileSync(FIXTURE, want);
    expect(readFileSync(FIXTURE, 'utf8')).toBe(want);
  });
});
