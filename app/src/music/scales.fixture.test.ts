// Parity between scales.ts and the engine's mirror (plan 26 Task 3,
// engine/src/rack/modules/theory.rs or similar): the fixture
// engine/tests/fixtures/scales.json is GENERATED from scales.ts here, and
// the Rust tests read it (a hand-rolled JSON reader, as auto_eval.json).
// This test fails when scales.ts and the committed fixture disagree, so a
// change to the maths is always a deliberate regeneration:
//   UPDATE_FIXTURES=1 npx vitest run app/src/music/scales.fixture.test.ts
//
// What it pins (indexes are the WIRE ORDER: SET_KEY's scale index, the
// Chord module's type index):
//   scales    [{ id, index, intervals, harmony }]
//   chords    [{ id, index, intervals | null }]
//   nearest   per scale x root: [[pitch, nearest, up, down], ...] over the
//             edges (0..12, 115..127) and one middle octave (54..72)
//   diatonic  per scale: degree 0..6 -> { triad, seventh } (root-relative)
//   voicings  [[rootPitch, typeIndex, inversion, root, scaleIndex, [pitches]]]
//             for every type x inversion on several roots and keys, edges
//             included
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { CHORD_TYPES, MAX_INVERSION, SCALES, SCALE_IDS, diatonicChord, nearestInKey, voiceChord } from './scales';
import type { MusicKey } from './scales';

const FIXTURE = new URL('../../../engine/tests/fixtures/scales.json', import.meta.url);

const PITCHES = [...range(0, 12), ...range(54, 72), ...range(115, 127)];
function range(a: number, b: number) {
  return Array.from({ length: b - a + 1 }, (_, i) => a + i);
}

/** JSON with one fixture row per line (diffs stay readable). */
function fixtureText(): string {
  const j = (v: unknown) => JSON.stringify(v);
  const out: string[] = ['{'];
  out.push(`  "version": 1,`);
  out.push(`  "about": ${j('Generated by app/src/music/scales.fixture.test.ts from app/src/music/scales.ts. Do not edit by hand. Indexes are wire order (SET_KEY scale index, Chord type index). nearest rows: [pitch, nearest (ties up), up, down]. voicings rows: [rootPitch, typeIndex, inversion, keyRoot, keyScaleIndex, pitches].')},`);
  out.push('  "scales": [');
  out.push(SCALE_IDS.map((id, index) => `    ${j({ id, index, intervals: SCALES[id].intervals, harmony: SCALE_IDS.indexOf(SCALES[id].harmony) })}`).join(',\n'));
  out.push('  ],');
  out.push('  "chords": [');
  out.push(CHORD_TYPES.map((c, index) => `    ${j({ id: c.id, index, intervals: c.intervals })}`).join(',\n'));
  out.push('  ],');
  out.push('  "nearest": [');
  const near: string[] = [];
  for (const [si, scale] of SCALE_IDS.entries()) {
    for (let root = 0; root < 12; root++) {
      const k: MusicKey = { root, scale };
      const rows = PITCHES.map((p) => [p, nearestInKey(p, k), nearestInKey(p, k, 'up'), nearestInKey(p, k, 'down')]);
      near.push(`    {"root": ${root}, "scale": ${si}, "rows": ${j(rows)}}`);
    }
  }
  out.push(near.join(',\n'));
  out.push('  ],');
  out.push('  "diatonic": [');
  out.push(SCALE_IDS.map((scale, si) => {
    const k: MusicKey = { root: 0, scale };
    const degrees = range(0, 6).map((d) => ({ triad: diatonicChord(k, d, false), seventh: diatonicChord(k, d, true) }));
    return `    {"scale": ${si}, "degrees": ${j(degrees)}}`;
  }).join(',\n'));
  out.push('  ],');
  out.push('  "voicings": [');
  const voic: string[] = [];
  const keys: MusicKey[] = [
    { root: 9, scale: 'minor' }, { root: 0, scale: 'major' }, { root: 2, scale: 'dorian' }, { root: 7, scale: 'mixolydian' },
    { root: 9, scale: 'harmonicMinor' }, { root: 4, scale: 'minorPentatonic' }, { root: 5, scale: 'majorPentatonic' }, { root: 3, scale: 'chromatic' },
  ];
  for (const k of keys) {
    for (const root of [0, 57, 61, 64, 120, 127]) {
      for (const [ti, c] of CHORD_TYPES.entries()) {
        for (let inv = 0; inv <= MAX_INVERSION; inv++) {
          voic.push(`    ${j([root, ti, inv, k.root, SCALE_IDS.indexOf(k.scale), voiceChord(root, c.id, inv, k)])}`);
        }
      }
    }
  }
  out.push(voic.join(',\n'));
  out.push('  ]');
  out.push('}');
  return out.join('\n') + '\n';
}

describe('scales fixture (engine parity)', () => {
  it('engine/tests/fixtures/scales.json matches scales.ts', () => {
    const text = fixtureText();
    if (process.env.UPDATE_FIXTURES === '1') writeFileSync(FIXTURE, text);
    const committed = readFileSync(FIXTURE, 'utf8');
    expect(committed, 'stale fixture: UPDATE_FIXTURES=1 npx vitest run app/src/music/scales.fixture.test.ts').toBe(text);
    // It is valid JSON with every section filled.
    const fx = JSON.parse(committed) as Record<string, unknown[]>;
    expect(fx.scales).toHaveLength(SCALE_IDS.length);
    expect(fx.chords).toHaveLength(CHORD_TYPES.length);
    expect(fx.nearest).toHaveLength(SCALE_IDS.length * 12);
    expect(fx.voicings.length).toBeGreaterThan(1000);
  });
});
